// Builds engine/recipes.js (the crafter's recipes) from the vanilla data pack inside a server jar
// extracted to a folder: node tools/gen-recipes.mjs <dir with data/minecraft/...>
// Kept: crafting_shaped, crafting_shapeless and crafting_transmute recipes, and the item tags their
// ingredients use (expanded to item lists). The special recipes (fireworks, banners, maps, repair,
// dyeing armour...) need item components and are left out.
import fs from 'node:fs';
import path from 'node:path';

const root = process.argv[2];
if (!root) throw new Error('usage: node tools/gen-recipes.mjs <extracted jar dir>');
const recipeDir = path.join(root, 'data/minecraft/recipe');
const tagDir = path.join(root, 'data/minecraft/tags/item');
const strip = (s) => s.replace(/^minecraft:/, '');

const tagCache = new Map();
function expandTag(name) {
  if (tagCache.has(name)) return tagCache.get(name);
  const file = path.join(tagDir, `${name}.json`);
  const out = [];
  tagCache.set(name, out);
  for (const v of JSON.parse(fs.readFileSync(file, 'utf8')).values) {
    const id = typeof v === 'string' ? v : v.id;
    if (id.startsWith('#')) out.push(...expandTag(strip(id.slice(1))));
    else out.push(strip(id));
  }
  return out;
}

const usedTags = new Set();
function ingredient(v) {
  if (Array.isArray(v)) return v.map(strip);
  const s = strip(v.startsWith('#') ? `#${strip(v.slice(1))}` : v);
  if (s.startsWith('#')) usedTags.add(s.slice(1));
  return s;
}

const recipes = [];
const skipped = {};
for (const f of fs.readdirSync(recipeDir).sort()) {
  if (!f.endsWith('.json')) continue;
  const id = f.slice(0, -5);
  const r = JSON.parse(fs.readFileSync(path.join(recipeDir, f), 'utf8'));
  const type = strip(r.type);
  if (type === 'crafting_shaped') {
    // ShapedRecipePattern.shrink: drop empty outer rows and columns
    let rows = r.pattern;
    let left = Infinity;
    let right = -1;
    for (const line of rows) {
      const first = line.search(/[^ ]/);
      if (first < 0) continue;
      left = Math.min(left, first);
      right = Math.max(right, line.length - 1 - [...line].reverse().join('').search(/[^ ]/));
    }
    rows = rows.filter((l) => /[^ ]/.test(l)).map((l) => l.padEnd(right + 1).slice(left, right + 1));
    const w = right - left + 1;
    const cells = rows.flatMap((l) => [...l].map((c) => (c === ' ' ? 0 : ingredient(r.key[c]))));
    recipes.push(['s', id, w, rows.length, cells, strip(r.result.id), r.result.count ?? 1]);
  } else if (type === 'crafting_shapeless') {
    recipes.push(['l', id, r.ingredients.map(ingredient), strip(r.result.id), r.result.count ?? 1]);
  } else if (type === 'crafting_transmute') {
    const mc = r.material_count;
    const bounds = mc === undefined ? [1, 1] : typeof mc === 'number' ? [mc, mc] : [mc.min ?? 1, mc.max ?? 8];
    recipes.push(['t', id, ingredient(r.input), ingredient(r.material), bounds, strip(r.result.id), r.result.count ?? 1, !!r.add_material_count_to_result]);
  } else if (type.startsWith('crafting')) {
    skipped[type] = (skipped[type] ?? 0) + 1;
  }
}

const tags = {};
for (const t of [...usedTags].sort()) tags[t] = expandTag(t);

const out = `// Generated by tools/gen-recipes.mjs from the vanilla 26.1.2 data pack: the crafting_shaped,
// crafting_shapeless and crafting_transmute recipes (sorted by id, the order RecipeManager tries
// them) and the item tags they use. Do not edit by hand.
// Shaped: ['s', id, width, height, cells, result, count]; shapeless: ['l', id, ingredients, result,
// count]; transmute: ['t', id, input, material, [min, max], result, count, addMaterialCount].
// An ingredient is an item id, '#tag', or a list of item ids; 0 is an empty cell.

export const TAGS = ${JSON.stringify(tags)};

export const RECIPES = [
${recipes.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
];
`;
fs.writeFileSync(new URL('../engine/recipes.js', import.meta.url), out);
console.log(`${recipes.length} recipes, ${Object.keys(tags).length} tags, ${(out.length / 1024).toFixed(0)} KB; left out:`, skipped);
